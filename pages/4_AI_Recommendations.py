score_out = predict_score(reg, meta_reg, engineered_df)

prob_val = float(risk_out["probabilities"][0])
tier_val = str(risk_out["risk_tiers"][0])
score_val = float(score_out[0])

# Compute Real SHAP Factors
shap_factors_list = []
try:
    explainer, preprocessor, feature_names = load_explainer_assets(scenario_code)
    explanation = explain_student(
        row=pd.Series(student_full_dict),
        explainer=explainer,
        preprocessor=preprocessor,
        feature_names=feature_names,
        top_n=5,
        is_classifier=True,
    )
    if explanation and not explanation["top_positive"].empty:
        for _, r in explanation["top_positive"].iterrows():
            shap_factors_list.append({
                "feature": str(r["feature"]),
                "shap_value": float(r["shap_value"]),
                "direction": "Elevates Risk",
            })
    if explanation and not explanation["top_negative"].empty:
        for _, r in explanation["top_negative"].iterrows():
            shap_factors_list.append({
                "feature": str(r["feature"]),
                "shap_value": float(r["shap_value"]),
                "direction": "Mitigates Risk",
            })
except Exception as shap_err:
    st.warning(f"SHAP attribution notice: {str(shap_err)}")

# Risk output dictionary for recommendation engines
