@st.cache_data(ttl=60)
def get_all_student_ids() -> list:
    """Fetch all unique student IDs from the database."""
    if not DATABASE_PATH.exists():
        return []
    with get_db_session() as session:
        ids = list(session.scalars(select(Student.student_id).order_by(Student.student_id)).all())
    return ids


@st.cache_data(ttl=30)
def get_student_details(student_id: str) -> dict:
    """Fetch student profile and academic records."""
    with get_db_session() as session:
        student = session.scalar(select(Student).where(Student.student_id == student_id))
        if not student:
            return {}

        acad = session.scalar(select(AcademicRecord).where(AcademicRecord.student_id == student_id))
        acad_dict = {}
        if acad:
            acad_dict = {
                "subject": acad.subject,
                "traveltime": acad.traveltime,
                "studytime": acad.studytime,
                "failures": acad.failures,
                "schoolsup": acad.schoolsup,
                "famsup": acad.famsup,
                "paid": acad.paid,
                "activities": acad.activities,
                "nursery": acad.nursery,
                "higher": acad.higher,
                "internet": acad.internet,
                "romantic": acad.romantic,
                "famrel": acad.famrel,
                "freetime": acad.freetime,
                "goout": acad.goout,
                "Dalc": acad.Dalc,
                "Walc": acad.Walc,
                "health": acad.health,
                "absences": acad.absences,
                "G1": acad.G1,
                "G2": acad.G2,
                "G3": acad.G3,
            }

        st_dict = {
            "student_id": student.student_id,
            "school": student.school,
            "sex": student.sex,
            "age": student.age,
            "address": student.address,
            "famsize": student.famsize,
            "Pstatus": student.Pstatus,
            "Medu": student.Medu,
            "Fedu": student.Fedu,
            "Mjob": student.Mjob,
            "Fjob": student.Fjob,
            "reason": student.reason,
            "guardian": student.guardian,
            "data_source": student.data_source,
        }
        return {"student": st_dict, "academic": acad_dict}


@st.cache_resource
def load_ml_models(scenario_code: str):
    """Load champion classifier and regressor for the selected scenario."""
    clf, meta_clf = load_classification_model(scenario_code)
    reg, meta_reg = load_model(scenario_code)
    return clf, meta_clf, reg, meta_reg


@st.cache_resource
def load_explainer_assets(scenario_code: str):
    """Load cached SHAP explainer."""
    return get_cached_explainer(scenario=scenario_code, model_type="classification")


