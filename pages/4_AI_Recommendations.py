clean_input = pd.DataFrame([student_full_dict])
clean_input = clean_input.drop(columns=["G3", "at_risk", "passed", "student_key", "student_id", "data_source"], errors="ignore")
engineered_df = add_engineered_features(clean_input, include_trend=is_scenario_b)

threshold = 0.15 if is_scenario_b else 0.25
