"""Unit Test Suite for EduGuard AI Regression Modeling & Loading (Stage 3).

Verifies:
1. `load_model()` successfully retrieves serialized pipelines and metadata for Scenarios A & B.
2. Predictions generated by loaded models fall strictly within [0.0, 20.0].
3. Target leakage prevention: passing G3 or at_risk into inference triggers ValueError.
4. Schema validation: missing required features triggers ValueError.
5. Educational performance hierarchy: Scenario B achieves significantly lower RMSE than Scenario A.
6. Metric computation accuracy with and without G3 == 0 rows.
"""

from pathlib import Path
import numpy as np
import pandas as pd
import pytest

from src.config import MODELS_DIR, PROCESSED_DATA_DIR, TARGET_COL
from src.features import prepare_scenario_data
from src.regression import (
    calculate_metrics,
    evaluate_model_comprehensive,
    load_model,
    predict_score,
    validate_inference_features,
)


@pytest.fixture(scope="module")
def test_data() -> pd.DataFrame:
    """Fixture providing processed test set."""
    return pd.read_csv(PROCESSED_DATA_DIR / "test.csv")


# ==============================================================================
# Test 1: Model Loading & Artifact Validation
# ==============================================================================
def test_load_model_artifacts_exist():
    """Verify load_model successfully loads persisted artifacts for both scenarios."""
    for scenario in ["A", "B"]:
        model, metadata = load_model(scenario=scenario)
        assert model is not None, f"Failed to load pipeline for Scenario {scenario}"
        assert isinstance(metadata, dict), f"Metadata for Scenario {scenario} is not a dictionary"
        assert "features_used" in metadata
        assert "test_metrics_all" in metadata
        assert "best_hyperparameters" in metadata


def test_load_model_missing_file_raises_error(tmp_path: Path):
    """Verify load_model raises FileNotFoundError when given non-existent paths."""
    fake_path = tmp_path / "non_existent_model.joblib"
    with pytest.raises(FileNotFoundError, match="Regression model file not found"):
        load_model(scenario="A", model_path=fake_path)


# ==============================================================================
# Test 2: Inference & Domain Bound Enforcement [0, 20]
# ==============================================================================
def test_predict_score_bounds(test_data: pd.DataFrame):
    """Verify predictions lie strictly within the valid Portuguese grading scale [0.0, 20.0]."""
    # Realistic inference input: future final grades G3 and at_risk are omitted
    inference_data = test_data.drop(columns=[TARGET_COL, "at_risk"], errors="ignore")

    for scenario in ["A", "B"]:
        model, metadata = load_model(scenario=scenario)
        preds = predict_score(model, metadata, inference_data)

        assert len(preds) == len(inference_data)
        assert not np.isnan(preds).any(), "NaN found in regression predictions."
        assert (preds >= 0.0).all(), "Found predictions below 0.0."
        assert (preds <= 20.0).all(), "Found predictions above 20.0."


# ==============================================================================
# Test 3: Data Leakage Prevention during Inference
# ==============================================================================
def test_inference_rejects_target_leakage(test_data: pd.DataFrame):
    """Verify that attempting to pass target columns into inference raises ValueError."""
    model, metadata = load_model(scenario="A")

    # test_data contains G3; validate_inference_features must reject it if present in candidate
    with pytest.raises(ValueError, match="DATA LEAKAGE ERROR"):
        validate_inference_features(test_data, metadata)


# ==============================================================================
# Test 4: Schema Validation (Missing Features)
# ==============================================================================
def test_inference_rejects_missing_features(test_data: pd.DataFrame):
    """Verify that omitting a required feature triggers a schema validation error."""
    model, metadata = load_model(scenario="A")

    # Drop a required predictor
    incomplete_df = test_data.drop(columns=["absences", TARGET_COL, "at_risk"], errors="ignore")

    with pytest.raises(ValueError, match="SCHEMA VALIDATION ERROR"):
        validate_inference_features(incomplete_df, metadata)


# ==============================================================================
# Test 5: Educational Performance Hierarchy (Scenario B vs Scenario A)
# ==============================================================================
def test_scenario_b_superiority(test_data: pd.DataFrame):
    """Verify Scenario B (with interim grades) achieves substantially lower RMSE than Scenario A."""
    _, meta_a = load_model(scenario="A")
    _, meta_b = load_model(scenario="B")

    rmse_a = meta_a["test_metrics_all"]["RMSE"]
    rmse_b = meta_b["test_metrics_all"]["RMSE"]

    # Scenario B RMSE must be less than half of Scenario A RMSE
    assert rmse_b < rmse_a, f"Expected Scenario B RMSE ({rmse_b}) < Scenario A RMSE ({rmse_a})"
    assert rmse_b <= 1.5, f"Scenario B RMSE ({rmse_b}) unexpectedly high."


# ==============================================================================
# Test 6: Metric Computation with and without G3 == 0 Rows
# ==============================================================================
def test_metric_computation_with_and_without_zeros(test_data: pd.DataFrame):
    """Verify comprehensive evaluation calculates separate statistics for all rows and non-zero rows."""
    model, metadata = load_model(scenario="A")
    X_test, y_test, _, _, _ = prepare_scenario_data(test_data, scenario="A")

    eval_results = evaluate_model_comprehensive(model, X_test, y_test)

    # Check key presence
    assert "test_mae_all" in eval_results
    assert "test_rmse_all" in eval_results
    assert "test_mae_nonzero" in eval_results
    assert "test_rmse_nonzero" in eval_results

    # Nonzero RMSE should differ from all-rows RMSE due to absence spikes at 0
    assert eval_results["test_zero_g3_count"] > 0
    assert eval_results["test_rmse_nonzero"] != eval_results["test_rmse_all"]
