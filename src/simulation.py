import numpy as np
import pandas as pd

from src.config import PROCESSED_DATA_DIR, RANDOM_STATE

DATA_SOURCE_TAG: str = "SIMULATED"


def simulate_student_weekly_trajectory(
    student_record: Dict[str, Any],
    student_id: str,
    n_weeks: int = 12,
    trajectory_type: str = "STABLE",
    rng: Optional[np.random.Generator] = None,
) -> List[Dict[str, Any]]:
    """Generate 12 weeks of synthetic academic monitoring logs for a single student.

    Anchors:
    - Base attendance: derived from historical absences (higher absences -> lower weekly attendance).
    - Base quiz average: derived from historical failures and interim grades (0 - 20 scale).
    - Base assignment completion: derived from study habits and support flags (0 - 100%).
    - Base study hours: derived from studytime category (1 to 4).

    Trajectories:
    - STABLE: Normal weekly fluctuations around baseline.
    - DECLINING: Normal in weeks 1-4, followed by progressive decline from week 5 onwards
      (attendance drops < 65%, quizzes drop by 5-8 pts, assignments plummet).
    - IMPROVING: Starts low in weeks 1-4, followed by positive upward trajectory.

    Args:
        student_record: Dictionary containing historical student attributes.
        student_id: Unique identifier for the student (e.g. 'EDU-0001').
        n_weeks: Number of academic weeks to simulate (default: 12).
        trajectory_type: 'STABLE', 'DECLINING', or 'IMPROVING'.
        rng: Seeded numpy random generator.

    Returns:
        List of weekly observation dictionaries.
    """
    if rng is None:
        rng = np.random.default_rng(RANDOM_STATE)

    # 1. Extract base student parameters
    absences = float(student_record.get("absences", 4.0))
    studytime = int(student_record.get("studytime", 2))
    failures = int(student_record.get("failures", 0))

    g1 = float(student_record.get("G1", 11.0))
    g2 = float(student_record.get("G2", 11.0))
    academic_anchor = (g1 + g2) / 2.0 if (pd.notna(g1) and pd.notna(g2)) else (12.0 - failures * 2.0)

    # 2. Derive base operational levels
    # Attendance: 98% base minus ~1% per absence, floor at 60%
    base_attendance = max(60.0, min(98.0, 96.0 - (absences / 20.0) * 16.0))

    # Quiz average: Portuguese 0-20 scale anchored to academic performance
    base_quiz = max(3.0, min(19.0, academic_anchor))

    # Assignment completion: 40% to 98%
    base_assignment = max(45.0, min(98.0, 90.0 + (studytime * 2.0) - (failures * 8.0)))

    # Study hours: studytime 1 (~2.5h), 2 (~5h), 3 (~8.5h), 4 (~13h)
    study_map = {1: 2.5, 2: 5.0, 3: 8.5, 4: 13.0}
    base_hours = study_map.get(studytime, 5.0)

    weekly_records = []

    for week in range(1, n_weeks + 1):
        # Base weekly noise
        att_noise = rng.normal(0.0, 3.5)
        quiz_noise = rng.normal(0.0, 1.2)
        assign_noise = rng.normal(0.0, 4.0)
        hours_noise = rng.normal(0.0, 0.8)

        # Apply trajectory modifier
        if trajectory_type == "DECLINING":
            if week <= 4:
                # Normal baseline in preliminary weeks
                att_mod = 0.0
                quiz_mod = 0.0
                assign_mod = 0.0
                hours_mod = 0.0
            else:
                # Progressive drop starting week 5
                decay_factor = week - 4
                att_mod = -decay_factor * 5.5       # By week 12: -44% drop
                quiz_mod = -decay_factor * 0.95     # By week 12: -7.6 pts drop
                assign_mod = -decay_factor * 6.5    # By week 12: -52% drop
                hours_mod = -decay_factor * 0.45    # By week 12: -3.6 hrs drop
        elif trajectory_type == "IMPROVING":
            if week <= 4:
                att_mod = -12.0
                quiz_mod = -2.5
                assign_mod = -15.0
                hours_mod = -1.5
            else:
                progress_factor = week - 4
                att_mod = -12.0 + (progress_factor * 2.2)
                quiz_mod = -2.5 + (progress_factor * 0.5)
                assign_mod = -15.0 + (progress_factor * 3.0)
                hours_mod = -1.5 + (progress_factor * 0.4)
        else:
            # STABLE
            att_mod = 0.0
            quiz_mod = 0.0
            assign_mod = 0.0
            hours_mod = 0.0

        # Calculate final clamped metrics
        weekly_att = float(np.clip(base_attendance + att_noise + att_mod, 10.0, 100.0))
        weekly_quiz = float(np.clip(base_quiz + quiz_noise + quiz_mod, 0.0, 20.0))
        weekly_assign = float(np.clip(base_assignment + assign_noise + assign_mod, 5.0, 100.0))
        weekly_hours = float(np.clip(base_hours + hours_noise + hours_mod, 0.5, 35.0))

        # Contextual notes for demonstration
        if trajectory_type == "DECLINING" and week >= 6:
            notes = f"SIMULATED: Observed steep decline in attendance and quiz scores (Week {week})."
        elif trajectory_type == "IMPROVING" and week >= 7:
            notes = f"SIMULATED: Positive recovery trend noted in assignment completion (Week {week})."
        else:
            notes = "SIMULATED: Standard weekly performance log."

        weekly_records.append({
            "student_id": student_id,
            "week_number": week,
            "attendance_rate": round(weekly_att, 2),
            "quiz_average": round(weekly_quiz, 2),
            "assignment_completion": round(weekly_assign, 2),
            "study_hours": round(weekly_hours, 2),
            "trajectory_type": trajectory_type,
            "notes": notes,
            "data_source": DATA_SOURCE_TAG,  # Explicit Rule 2.1 flag
        })

    return weekly_records


def generate_simulated_weekly_dataset(
    df_students: pd.DataFrame,
    n_weeks: int = 12,
    declining_ratio: float = 0.08,
    improving_ratio: float = 0.06,
    random_state: int = RANDOM_STATE,
    output_path: Optional[Union[str, Path]] = None,
) -> pd.DataFrame:
    """Generate longitudinal synthetic weekly performance data for a cohort of students.

    Args:
        df_students: DataFrame containing student rows (e.g. from test.csv).
        n_weeks: Number of weeks to simulate per student (default: 12).
        declining_ratio: Fraction of students assigned a declining trajectory (demo alerts).
        improving_ratio: Fraction of students assigned an improving trajectory.
        random_state: Seed for reproducibility.
        output_path: Optional path to persist the generated CSV.

    Returns:
        pd.DataFrame containing simulated weekly records with data_source = 'SIMULATED'.
    """
    rng = np.random.default_rng(random_state)
    n_students = len(df_students)

    # Assign student IDs if not already present
    df_work = df_students.copy()
    if "student_id" not in df_work.columns:
        df_work["student_id"] = [f"EDU-{i+1:04d}" for i in range(n_students)]

    # Deterministically select declining and improving cohorts
    indices = np.arange(n_students)
    rng.shuffle(indices)

    n_declining = max(2, int(n_students * declining_ratio))
    n_improving = max(2, int(n_students * improving_ratio))

    declining_set = set(indices[:n_declining])
    improving_set = set(indices[n_declining : n_declining + n_improving])

    all_weekly_rows = []

    for idx, (_, row) in enumerate(df_work.iterrows()):
        st_id = row["student_id"]

        if idx in declining_set:
            traj = "DECLINING"
        elif idx in improving_set:
            traj = "IMPROVING"
        else:
            traj = "STABLE"

        student_dict = row.to_dict()
        student_weekly = simulate_student_weekly_trajectory(
            student_record=student_dict,
            student_id=st_id,
            n_weeks=n_weeks,
            trajectory_type=traj,
            rng=rng,
        )
        all_weekly_rows.extend(student_weekly)

    df_simulated = pd.DataFrame(all_weekly_rows)

    # Persist if output_path is specified
    if output_path is None:
        output_path = PROCESSED_DATA_DIR / "simulated_weekly_performance.csv"
    
    out_p = Path(output_path)
    out_p.parent.mkdir(parents=True, exist_ok=True)
    df_simulated.to_csv(out_p, index=False)

    return df_simulated


